    /**
     * 农历转公历
     */
    public static function toSolar(int $year, int $month, int $day): ?string
    {
        if ($year < 1900 || $year > 2100 || $month < 1 || $month > 12 || $day < 1 || $day > 30) {
            return null;
        }

        // 计算1900-01-31到目标日期的天数
        $offset = 0;
        for ($y = 1900; $y < $year; $y++) {
            $offset += self::yearDays($y);
        }

        $info = self::$data[$year - 1900];
        $leap = $info & 0xf;
        $hasLeap = $leap > 0;

        // 累加该年内月份
        for ($m = 1; $m < $month; $m++) {
            $offset += self::monthDays($year, $m);
        }
        // 如果闰月在目标月之前，加上闰月天数
        if ($hasLeap && $leap < $month) {
            $offset += self::leapDays($year);
        }
        $offset += $day - 1;

        // 1900-01-31 + offset → 公历
        return date('Y-m-d', mktime(0, 0, 0, 1, 31, 1900) + $offset * 86400);
    }

    /** 农历年总天数 */
    private static function yearDays(int $year): int
    {
        $days = 0;
        $info = self::$data[$year - 1900];
        for ($i = 0; $i < 12; $i++) {
            $days += (($info >> (4 + $i)) & 1) ? 30 : 29;
        }
        return $days + self::leapDays($year);
    }

    /** 农历月天数 */
    private static function monthDays(int $year, int $month): int
    {
        return ((self::$data[$year - 1900] >> (4 + $month - 1)) & 1) ? 30 : 29;
    }

    /** 闰月天数（0=无闰月） */
    private static function leapDays(int $year): int
    {
        $info = self::$data[$year - 1900];
        $leap = $info & 0xf;
        return $leap > 0 ? (((($info >> 16) & 1) ? 30 : 29)) : 0;
    }
